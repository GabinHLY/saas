const dicts = { fr, en };

export function makeI18n(lang) {
  const t = dicts[lang] || fr,
    loc = lang === "en" ? "en-GB" : "fr-FR";
  return {
    lang,
    t,
    loc,
    money: (n) =>
      new Intl.NumberFormat(loc, {
        style: "currency",
        currency: "EUR",
        maximumFractionDigits: (n || 0) % 100 ? 2 : 0,
      }).format((n || 0) / 100),
    num: (n) => new Intl.NumberFormat(loc).format(n || 0),
    dec: (n) =>
      new Intl.NumberFormat(loc, {
        minimumFractionDigits: 1,
        maximumFractionDigits: 1,
      }).format(n || 0),
    longDate: (iso) =>
      new Date(iso.slice(0, 10) + "T12:00").toLocaleDateString(loc, {
        day: "numeric",
        month: "long",
        year: "numeric",
      }),
    category: (c) => t.category[c?.toUpperCase()] || c?.toLowerCase() || "",
  };
}

export const useI18n = () => makeI18n(useContext(LangContext));
